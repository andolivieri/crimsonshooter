GameMap::GameMap(SDL_Renderer* ren):
    m_renderer(ren)
{
    LoadMap(lvl1);
    dirt = TextureManager::loadTexture("assets/dirt.png");
    grass = TextureManager::loadTexture("assets/grass.png");
    water = TextureManager::loadTexture("assets/water.png");
}

GameMap::~GameMap()
{
}

void GameMap::DrawMap()
{
    for(int i = 0; i< MAP_ROWS; i++){
        for(int j = 0; j < MAP_COLS; j++){

            SDL_Texture* tex = nullptr;
            switch (map[i][j]) {
            case GameMap::DIRT:
                tex = dirt;
                break;
            case GameMap::GRASS:
                tex = grass;
                break;
            case GameMap::WATER:
            default:
                tex = water;
                break;
            }

            SDL_Rect src;
            src.h = src.w = TILESIZE;
            src.x = src.y = 0;

            int zoom = 1;

            SDL_Rect dst;
            dst.h = dst.w = zoom*TILESIZE;
            dst.x = zoom*TILESIZE*j;
            dst.y = zoom*TILESIZE*i;

            TextureManager::drawTexture(tex, src, dst);
        }
    }
}

void GameMap::LoadMap(int arr[MAP_ROWS][MAP_COLS])
{
    for(int i = 0; i< MAP_ROWS; i++){
        for(int j = 0; j < MAP_COLS; j++){
            map[i][j] = arr[i][j];
        }
    }
}
